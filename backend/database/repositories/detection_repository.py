"""
Detection Repository
====================
Persistence operations for AI defect detection runs and individual bounding-box defect detections.
"""

from typing import List, Optional, Dict, Any
from sqlalchemy.orm import Session
from backend.db.models import DetectionRun, Detection


class DetectionRepository:
    def __init__(self, session: Session):
        self.session = session

    def create_detection_run(self, data: Dict[str, Any]) -> DetectionRun:
        """Persists a new AI defect inference run."""
        run = DetectionRun(**data)
        self.session.add(run)
        self.session.flush()
        return run

    def save_detections(self, detections_data: List[Dict[str, Any]]) -> List[Detection]:
        """Bulk persists individual defect detections linked to an inference run."""
        detections = [Detection(**d) for d in detections_data]
        self.session.add_all(detections)
        self.session.flush()
        return detections

    def get_detections_for_run(self, run_id: str) -> List[Detection]:
        """Retrieves all defect detections generated by a specific run."""
        return (
            self.session.query(Detection)
            .filter_by(detection_run_id=run_id)
            .order_by(Detection.confidence.desc())
            .all()
        )

    def get_detections_for_evidence(self, evidence_asset_id: str) -> List[Detection]:
        """Retrieves all defect detections across runs linked to an evidence asset."""
        return (
            self.session.query(Detection)
            .filter_by(evidence_asset_id=evidence_asset_id)
            .order_by(Detection.confidence.desc())
            .all()
        )

    def get_by_id(self, detection_id: str) -> Optional[Detection]:
        """Retrieves an individual detection by primary UUID."""
        return self.session.query(Detection).filter_by(id=detection_id).first()
